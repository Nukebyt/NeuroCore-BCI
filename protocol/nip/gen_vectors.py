"""Generate protocol/nip/vectors.json and tests/c/nip_vectors.h (spec §9).

Usage: python -m protocol.nip.gen_vectors
"""

from __future__ import annotations

import json
from pathlib import Path

from protocol.nip.nip import Flags, Frame, Intent, Status, encode, pack_unchecked, seq_is_newer

NIP_DIR = Path(__file__).resolve().parent

_VALID: list[tuple[str, Frame]] = [
    ("heartbeat_stop_t0", Frame(seq=0, t_ms=0, intent=Intent.STOP)),
    *(
        (
            f"intent_{i.name.lower()}",
            Frame(seq=i.value + 1, t_ms=1000 + 40 * i.value, intent=i, level=1),
        )
        for i in Intent
        if i is not Intent.STOP
    ),
    (
        "all_fields_max",
        Frame(
            seq=255,
            t_ms=0xFFFFFFFF,
            intent=Intent.AUX_B,
            level=3,
            confidence=255,
            flags=Flags(0x1F),
        ),
    ),
    ("seq_wrapped_to_zero", Frame(seq=0, t_ms=10240, intent=Intent.HOLD, level=2, confidence=128)),
    (
        "latched_stop_flag",
        Frame(seq=42, t_ms=123456, intent=Intent.STOP, flags=Flags.CALIBRATED | Flags.LATCHED_STOP),
    ),
    (
        "artifact_and_channel_bad",
        Frame(
            seq=99,
            t_ms=65536,
            intent=Intent.LEFT,
            level=1,
            confidence=17,
            flags=Flags.ARTIFACT | Flags.CHANNEL_BAD,
        ),
    ),
]


def _invalid() -> list[tuple[str, bytes, Status]]:
    good = encode(Frame(seq=5, t_ms=2000, intent=Intent.FWD, level=2, confidence=90))
    bad_crc = bytearray(good)
    bad_crc[14] ^= 0x01
    base = {"seq": 5, "t_ms": 2000, "intent": 2, "level": 2, "confidence": 90, "flags": 0}
    return [
        ("empty", b"", Status.LEN),
        ("short_15", good[:15], Status.LEN),
        ("long_17", good + b"\x00", Status.LEN),
        ("bad_magic", pack_unchecked(**base, magic=0x504E), Status.MAGIC),
        ("version_1", pack_unchecked(**base, version=1), Status.VERSION),
        ("crc_bit_flipped", bytes(bad_crc), Status.CRC),
        ("payload_bit_flipped", good[:9] + bytes([good[9] ^ 0x01]) + good[10:], Status.CRC),
        ("intent_9", pack_unchecked(**{**base, "intent": 9}), Status.INTENT),
        ("level_4", pack_unchecked(**{**base, "level": 4}), Status.LEVEL),
        ("flags_bit5", pack_unchecked(**{**base, "flags": 0x20}), Status.FLAGS),
        ("reserved_1", pack_unchecked(**base, reserved=1), Status.RESERVED),
    ]


_SEQ_PAIRS = [(1, 0), (0, 255), (127, 0), (128, 0), (0, 0), (200, 100), (100, 200), (5, 250)]


def build() -> dict:
    return {
        "spec": "protocol/nip/spec.md",
        "generated_by": "python -m protocol.nip.gen_vectors",
        "crc_check": {"input_ascii": "123456789", "crc16": "0x29B1"},
        "valid": [
            {
                "name": name,
                "fields": {
                    "seq": f.seq,
                    "t_ms": f.t_ms,
                    "intent": int(f.intent),
                    "level": f.level,
                    "confidence": f.confidence,
                    "flags": int(f.flags),
                },
                "bytes": encode(f).hex(),
            }
            for name, f in _VALID
        ],
        "invalid": [
            {"name": name, "bytes": raw.hex(), "error": status.name}
            for name, raw, status in _invalid()
        ],
        "seq_is_newer": [
            {"candidate": c, "last": last, "newer": seq_is_newer(c, last)} for c, last in _SEQ_PAIRS
        ],
    }


def _c_bytes(hex_str: str) -> str:
    raw = bytes.fromhex(hex_str)
    return "{" + ", ".join(f"0x{b:02X}" for b in raw) + "}" if raw else "{0}"


def render_c(vectors: dict) -> str:
    lines = [
        "/* GENERATED by `python -m protocol.nip.gen_vectors` from vectors.json. Do not edit. */",
        "#ifndef NIP_VECTORS_H",
        "#define NIP_VECTORS_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "/* clang-format off */",
        "",
        "typedef struct {",
        "    const char *name;",
        "    uint8_t seq;",
        "    uint32_t t_ms;",
        "    uint8_t intent;",
        "    uint8_t level;",
        "    uint8_t confidence;",
        "    uint8_t flags;",
        "    uint8_t bytes[16];",
        "} nip_valid_vector_t;",
        "",
        "typedef struct {",
        "    const char *name;",
        "    uint8_t bytes[32];",
        "    size_t len;",
        "    int status;",
        "} nip_invalid_vector_t;",
        "",
        "typedef struct {",
        "    uint8_t candidate;",
        "    uint8_t last;",
        "    int newer;",
        "} nip_seq_vector_t;",
        "",
        "static const nip_valid_vector_t NIP_VALID_VECTORS[] = {",
    ]
    for v in vectors["valid"]:
        f = v["fields"]
        lines.append(
            f'    {{"{v["name"]}", {f["seq"]}u, {f["t_ms"]}u, {f["intent"]}u, {f["level"]}u, '
            f'{f["confidence"]}u, {f["flags"]}u, {_c_bytes(v["bytes"])}}},'
        )
    lines += ["};", "", "static const nip_invalid_vector_t NIP_INVALID_VECTORS[] = {"]
    for v in vectors["invalid"]:
        n = len(bytes.fromhex(v["bytes"]))
        lines.append(
            f'    {{"{v["name"]}", {_c_bytes(v["bytes"])}, {n}u, {Status[v["error"]].value}}},'
        )
    lines += ["};", "", "static const nip_seq_vector_t NIP_SEQ_VECTORS[] = {"]
    for v in vectors["seq_is_newer"]:
        lines.append(f'    {{{v["candidate"]}u, {v["last"]}u, {int(v["newer"])}}},')
    lines += [
        "};",
        "",
        "#define NIP_N_VALID (sizeof NIP_VALID_VECTORS / sizeof NIP_VALID_VECTORS[0])",
        "#define NIP_N_INVALID (sizeof NIP_INVALID_VECTORS / sizeof NIP_INVALID_VECTORS[0])",
        "#define NIP_N_SEQ (sizeof NIP_SEQ_VECTORS / sizeof NIP_SEQ_VECTORS[0])",
        "",
        "/* clang-format on */",
        "",
        "#endif /* NIP_VECTORS_H */",
        "",
    ]
    return "\n".join(lines)


def render() -> tuple[str, str]:
    vectors = build()
    return json.dumps(vectors, indent=2) + "\n", render_c(vectors)


def main() -> None:
    json_text, c_header = render()
    (NIP_DIR / "vectors.json").write_text(json_text, encoding="utf-8", newline="\n")
    (NIP_DIR / "tests" / "c").mkdir(parents=True, exist_ok=True)
    (NIP_DIR / "tests" / "c" / "nip_vectors.h").write_text(c_header, encoding="utf-8", newline="\n")
    print("wrote vectors.json and tests/c/nip_vectors.h")


if __name__ == "__main__":
    main()
