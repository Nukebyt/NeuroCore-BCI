"""Export DSP coefficients and cross-check vectors for firmware/neurocore/dsp.

Writes:
  firmware/neurocore/dsp/dsp_coeffs.h        SOS coefficients designed in ml/features/filters.py
  firmware/neurocore/dsp/tests/dsp_vectors.h expected outputs for the shared test input

Shared test input (must match test_dsp.c): xorshift32 seeded with 12345,
  u = (next() >> 8) / 2^24 * 2 - 1;  x[n] = u * (80 if n in BURSTS else 5)   [µV]
  BURSTS = [500, 1200) U [2000, 2600), N = 3000 samples at 1 kHz.

Usage: python -m ml.export.gen_dsp
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
from scipy import signal

from ml.features.emg import DEBOUNCE_MS, EnvelopeTracker, HysteresisDetector, Thresholds
from ml.features.filters import emg_sos, notch_sos
from ml.intent.gen_fsm_vectors import XorShift32

ROOT = Path(__file__).resolve().parents[2]
COEFFS = ROOT / "firmware" / "neurocore" / "dsp" / "dsp_coeffs.h"
VECTORS = ROOT / "firmware" / "neurocore" / "dsp" / "tests" / "dsp_vectors.h"

EMG_FS = 1000.0
EEG_FS = 250.0
N = 3000
BURSTS = [(500, 1200), (2000, 2600)]
CHECK_EVERY = 50
TEST_THRESHOLDS = Thresholds(on_uv=20.0, off_uv=12.0)


def test_input() -> np.ndarray:
    rng = XorShift32(12345)
    x = np.empty(N)
    for n in range(N):
        u = (rng.next() >> 8) / float(1 << 24) * 2.0 - 1.0
        amp = 80.0 if any(a <= n < b for a, b in BURSTS) else 5.0
        x[n] = u * amp
    return x


def _sos_c(name: str, sos: np.ndarray) -> list[str]:
    lines = [f"#define {name}_N_SECTIONS {sos.shape[0]}u", f"static const float {name}[][6] = {{"]
    for row in sos:
        lines.append("    {" + ", ".join(f"{v:.9e}f" for v in row) + "},")
    return [*lines, "};", ""]


def render_coeffs() -> str:
    return "\n".join(
        [
            "/* GENERATED by `python -m ml.export.gen_dsp` from ml/features/filters.py. */",
            "/* Each row: b0 b1 b2 a0 a1 a2 (a0 == 1). Do not edit. */",
            "#ifndef DSP_COEFFS_H",
            "#define DSP_COEFFS_H",
            "",
            "/* clang-format off */",
            *_sos_c("EMG_SOS_1KHZ", emg_sos(EMG_FS)),
            *_sos_c("EEG_NOTCH_SOS_250HZ", notch_sos(EEG_FS)),
            "/* clang-format on */",
            "",
            "#endif /* DSP_COEFFS_H */",
            "",
        ]
    )


def expected() -> tuple[np.ndarray, list[float], list[tuple[int, int]]]:
    """(filtered checkpoints, envelope values, detector transitions as (t_ms, state))."""
    x = test_input()
    y = signal.sosfilt(emg_sos(EMG_FS), x)
    env = EnvelopeTracker(EMG_FS)
    det = HysteresisDetector(TEST_THRESHOLDS, DEBOUNCE_MS)
    envs, transitions, state = [], [], False
    for n, v in enumerate(y):
        for e in env.process(np.array([v])):
            envs.append(e)
            t_ms = n  # 1 kHz: sample index == ms
            if det.update(e, t_ms) != state:
                state = det.active
                transitions.append((t_ms, int(state)))
    return y[::CHECK_EVERY], envs, transitions


def render_vectors() -> str:
    checks, envs, transitions = expected()
    fl = lambda vals: "\n".join(f"    {v:.6e}f," for v in vals)  # noqa: E731
    return "\n".join(
        [
            "/* GENERATED by `python -m ml.export.gen_dsp`. Do not edit. */",
            "#ifndef DSP_VECTORS_H",
            "#define DSP_VECTORS_H",
            "",
            "/* clang-format off */",
            f"#define DSP_N_SAMPLES {N}u",
            f"#define DSP_CHECK_EVERY {CHECK_EVERY}u",
            f"#define DSP_TEST_ON_UV {TEST_THRESHOLDS.on_uv}f",
            f"#define DSP_TEST_OFF_UV {TEST_THRESHOLDS.off_uv}f",
            "static const float DSP_FILTER_CHECKS[] = {",
            fl(checks),
            "};",
            "static const float DSP_ENVELOPE[] = {",
            fl(envs),
            "};",
            "#define DSP_N_ENVELOPE (sizeof DSP_ENVELOPE / sizeof DSP_ENVELOPE[0])",
            "static const unsigned DSP_TRANSITIONS[][2] = {",
            *(f"    {{{t}u, {s}u}}," for t, s in transitions),
            "};",
            "#define DSP_N_TRANSITIONS (sizeof DSP_TRANSITIONS / sizeof DSP_TRANSITIONS[0])",
            "/* clang-format on */",
            "",
            "#endif /* DSP_VECTORS_H */",
            "",
        ]
    )


def main() -> None:
    VECTORS.parent.mkdir(parents=True, exist_ok=True)
    COEFFS.write_text(render_coeffs(), encoding="utf-8", newline="\n")
    VECTORS.write_text(render_vectors(), encoding="utf-8", newline="\n")
    _, envs, transitions = expected()
    print(f"wrote dsp_coeffs.h, dsp_vectors.h: {len(envs)} envelope values, {transitions}")


if __name__ == "__main__":
    main()
