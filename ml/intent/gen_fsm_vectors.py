"""Cross-language check for the intent FSM (Python reference <-> firmware C port).

Both sides build the same pseudo-random sessions from xorshift32 seeds (spec below), run
their FSM, and hash every output with FNV-1a. This script writes the expected hashes to
firmware/neurocore/intent/tests/fsm_vectors.h.

Session spec (must match fsm_session.c exactly):
  rng = xorshift32(seed); n_segments = 1 + next() % 30
  per segment: c = next() % 2 (drawn first); n_ticks = c ? 1 + next() % 8 : 1 + next() % 60
               arms    = ARMS[next() % 7]     ARMS = (0,0)x4, (1,0), (0,1), (1,1)
               ssvep   = SSVEPS[next() % 5]   SSVEPS = N, N, N, PLUS, MINUS
               artifact = next() % 8 == 0;  channel_bad = next() % 9 == 0
               calibrated = next() % 13 != 0;  fault = next() % 41 == 0 (first tick only)
  t_ms starts at 0 and advances 40 per tick.
Per step, hash bytes: intent (0xFF when not emitting), level, flags.

Usage: python -m ml.intent.gen_fsm_vectors
"""

from __future__ import annotations

import itertools
from pathlib import Path

from ml.intent.fsm import FsmState, Inputs, Mode, Output, step
from ml.models.classical.ssvep import Ssvep

ROOT = Path(__file__).resolve().parents[2]
HEADER = ROOT / "firmware" / "neurocore" / "intent" / "tests" / "fsm_vectors.h"
SEEDS = range(1, 301)
TICK_MS = 40
_M = 0xFFFFFFFF
ARMS = [(False, False)] * 4 + [(True, False), (False, True), (True, True)]
SSVEPS = [Ssvep.NONE] * 3 + [Ssvep.PLUS, Ssvep.MINUS]


class XorShift32:
    def __init__(self, seed: int) -> None:
        self.x = seed & _M

    def next(self) -> int:
        x = self.x
        x ^= (x << 13) & _M
        x ^= x >> 17
        x ^= (x << 5) & _M
        self.x = x & _M
        return self.x


def session_inputs(seed: int) -> list[Inputs]:
    rng = XorShift32(seed)
    out: list[Inputs] = []
    t = 0
    for _ in range(1 + rng.next() % 30):
        n = (1 + rng.next() % 8) if rng.next() % 2 else (1 + rng.next() % 60)
        left, right = ARMS[rng.next() % 7]
        ssvep = SSVEPS[rng.next() % 5]
        artifact = rng.next() % 8 == 0
        bad = rng.next() % 9 == 0
        cal = rng.next() % 13 != 0
        fault = rng.next() % 41 == 0
        for k in range(n):
            out.append(Inputs(t, left, right, ssvep, artifact, bad, cal, fault and k == 0))
            t += TICK_MS
    return out


def fnv1a(outputs: list[Output]) -> int:
    h = 0x811C9DC5
    for o in outputs:
        intent = 0xFF if o.intent is None else int(o.intent)
        for b in (intent, o.level, int(o.flags)):
            h = ((h ^ b) * 0x01000193) & _M
    return h


def run_session(seed: int) -> tuple[list[FsmState], list[Output]]:
    s, states, outs = FsmState(), [], []
    for i in session_inputs(seed):
        s, o = step(s, i)
        states.append(s)
        outs.append(o)
    return states, outs


def coverage() -> dict[str, int]:
    """How many sessions exercise each behaviour (so the hash check means something)."""
    cov = {"stopped": 0, "latch_cleared": 0, "reverse_toggled": 0, "fault": 0, "level3": 0}
    for seed in SEEDS:
        states, outs = run_session(seed)
        modes = [s.mode for s in states]
        cov["stopped"] += Mode.STOPPED in modes
        cov["latch_cleared"] += any(
            a is Mode.STOPPED and b not in (Mode.STOPPED, Mode.FAULT)
            for a, b in itertools.pairwise(modes)
        )
        cov["reverse_toggled"] += any(s.reverse for s in states)
        cov["fault"] += Mode.FAULT in modes
        cov["level3"] += any(o.level == 3 for o in outs)
    return cov


def render() -> str:
    rows = []
    for seed in SEEDS:
        _, outs = run_session(seed)
        rows.append(f"    {{{seed}u, {len(outs)}u, 0x{fnv1a(outs):08X}u}},")
    return "\n".join(
        [
            "/* GENERATED by `python -m ml.intent.gen_fsm_vectors`. Do not edit. */",
            "#ifndef FSM_VECTORS_H",
            "#define FSM_VECTORS_H",
            "",
            "#include <stdint.h>",
            "",
            "/* clang-format off */",
            "typedef struct {",
            "    uint32_t seed;",
            "    uint32_t n_steps;",
            "    uint32_t hash;",
            "} fsm_vector_t;",
            "",
            "static const fsm_vector_t FSM_VECTORS[] = {",
            *rows,
            "};",
            "#define FSM_N_VECTORS (sizeof FSM_VECTORS / sizeof FSM_VECTORS[0])",
            "/* clang-format on */",
            "",
            "#endif /* FSM_VECTORS_H */",
            "",
        ]
    )


def main() -> None:
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {HEADER.relative_to(ROOT)}; coverage {coverage()}")


if __name__ == "__main__":
    main()
